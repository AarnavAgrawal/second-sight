// Copies the shared/ modules the actor imports (and everything they import) into actor/src/shared/,
// because `terse deploy` uploads only the actor project folder. shared/ stays the single source of truth;
// actor/src/shared/ is generated and gitignored.
//   bun scripts/sync-actor-shared.ts
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sharedDir = join(root, "shared");
const actorSrc = join(root, "actor", "src");
const outDir = join(actorSrc, "shared");

const importsOf = (src: string) => [...src.matchAll(/from\s+"\.\/([\w.-]+\.ts)"/g)].map((m) => m[1]!);

// Entry points: shared files imported by the actor source.
const actorFiles = readdirSync(actorSrc).filter((f) => f.endsWith(".ts"));
const entries = new Set<string>();
for (const f of actorFiles) {
  const src = readFileSync(join(actorSrc, f), "utf8");
  for (const m of src.matchAll(/from\s+"\.\/shared\/([\w.-]+\.ts)"/g)) entries.add(m[1]!);
}

// Transitive closure within shared/.
const needed = new Set<string>();
const queue = [...entries];
while (queue.length) {
  const f = queue.pop()!;
  if (needed.has(f)) continue;
  needed.add(f);
  for (const dep of importsOf(readFileSync(join(sharedDir, f), "utf8"))) queue.push(dep);
}

mkdirSync(outDir, { recursive: true });
// Remove copies that are no longer needed; write only changed files (the dev server reloads on every write).
for (const f of readdirSync(outDir)) if (!needed.has(f)) rmSync(join(outDir, f), { force: true });
let changed = 0;
for (const f of [...needed].sort()) {
  const banner = `// GENERATED by scripts/sync-actor-shared.ts from shared/${f}. Edit shared/${f}, not this copy.\n`;
  const content = banner + readFileSync(join(sharedDir, f), "utf8");
  const target = join(outDir, f);
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    /* new file */
  }
  if (current !== content) {
    writeFileSync(target, content);
    changed++;
  }
}
if (changed || !process.argv.includes("--quiet")) console.log(`actor/src/shared: ${[...needed].sort().join(", ")} (${changed} updated)`);
